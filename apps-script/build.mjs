// Bundles apps-script/main.ts (+ the shared server/logic.ts) into one file to paste into the Apps Script editor.
import { build } from 'esbuild'

// Apps Script only runs top-level functions, so expose the bundle's exports as plain global functions.
const entry = ['doPost', 'doGet', 'setup', 'installTriggers', 'recalculateJob', 'refreshViewsJob', 'onOpen']
const footer = entry.map((f) => `function ${f}(e) { return ZCL.${f}(e) }`).join('\n')

await build({
  entryPoints: ['apps-script/main.ts'],
  bundle: true,
  format: 'iife',
  globalName: 'ZCL',
  target: 'es2019',
  charset: 'utf8',
  outfile: 'apps-script/Code.js',
  banner: { js: '// GENERATED by `npm run build:gas` from apps-script/*.ts and server/logic.ts. Edit those files, not this one.' },
  footer: { js: footer },
})
console.log('apps-script/Code.js written')
